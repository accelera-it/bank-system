#!/bin/bash
# Runs once, on the first start of an empty volume: each app gets its own user, which is its schema.
sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT FAILURE
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER PROFILE DEFAULT LIMIT PASSWORD_LIFE_TIME UNLIMITED;
CREATE USER BankSystem IDENTIFIED BY "$ORACLE_PASSWORD" QUOTA UNLIMITED ON USERS;
GRANT DB_DEVELOPER_ROLE TO BankSystem;
CREATE USER CentralApi IDENTIFIED BY "$ORACLE_PASSWORD" QUOTA UNLIMITED ON USERS;
GRANT DB_DEVELOPER_ROLE TO CentralApi;
SQL
