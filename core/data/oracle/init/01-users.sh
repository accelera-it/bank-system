#!/bin/bash
# Runs once, on the first start of an empty volume: one schema per app.
sqlplus -s / as sysdba <<EOF
WHENEVER SQLERROR EXIT FAILURE
ALTER SESSION SET CONTAINER=FREEPDB1;
CREATE USER banksystem IDENTIFIED BY "${BANK_DB_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CONNECT, RESOURCE TO banksystem;
CREATE USER centralapi IDENTIFIED BY "${CENTRALAPI_DB_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CONNECT, RESOURCE TO centralapi;
EOF
